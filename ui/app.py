if nav_mode == "📊 Schedule Visualizer":
    st.title("📊 Production Schedule Visualizer")
    st.markdown(
        "Interactive Gantt chart generated by **OR-Tools CP-SAT** with sequence-dependent "
        "changeover setups, planned maintenance windows, and decision tracing."
    )

    sched: Schedule = st.session_state.schedule_current

    # Top KPI Metrics Cards
    col1, col2, col3, col4, col5 = st.columns(5)
    with col1:
        st.metric("Makespan", f"{sched.kpis.makespan} min")
    with col2:
        otd_val = f"{sched.kpis.on_time_pct:.1f}%"
        delta_otd = (
            f"{sched.kpis.on_time_pct - st.session_state.schedule_baseline.kpis.on_time_pct:+.1f}%"
            if sched != st.session_state.schedule_baseline
            else None
        )
        st.metric("On-Time Delivery", otd_val, delta=delta_otd)
    with col3:
        st.metric("Total Tardiness", f"{sched.kpis.total_tardiness} min")
    with col4:
        st.metric("Total Setup Time", f"{sched.kpis.total_setup_time} min")
    with col5:
        st.metric("Solver Status", sched.solver_stats.status)

    # Plotly Interactive Gantt
    st.plotly_chart(
        create_gantt_chart(sched, plant, title="Factory Floor Execution Horizon", height=420),
        use_container_width=True,
    )

    # Assignments Inspector Table
    with st.expander("🔍 Detailed Operation Assignments Table", expanded=False):
        records: list[dict[str, Any]] = []
        for a in sched.assignments:
            ord_obj = plant.order_by_id(a.order_id)
            mat_id = ord_obj.material_id if ord_obj else "N/A"
            mat_obj = plant.material_by_id(mat_id) if ord_obj else None
            mat_info = mat_obj.family.value if (mat_obj and mat_obj.family) else mat_id
            tcs = [tc.value for tc in a.tight_constraints]
            tc_str = ", ".join(tcs) if tcs else "NONE"

            records.append(
                {
                    "Order ID": a.order_id,
                    "Operation": a.operation_id,
                    "Machine": a.machine_id,
                    "Start (min)": a.start,
                    "End (min)": a.end,
                    "Duration (min)": a.processing_time,
                    "Setup (min)": a.setup_time,
                    "Material": mat_info,
                    "Tight Constraint": tc_str,
                }
            )
        df_assign = pd.DataFrame(records).sort_values(by=["Machine", "Start (min)"])
        st.dataframe(df_assign, use_container_width=True, hide_index=True)


